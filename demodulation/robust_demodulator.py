def test_bpsk():

    original = "10110010"

    # Generate ideal BPSK symbols.
    symbols = np.array(
        [
            1 if bit == "1"
            else -1
            for bit in original
        ],
        dtype=np.complex64
    )

    # Repeat each symbol 100 times,
    # just like dataset_generator.py.
    iq = np.repeat(
        symbols,
        DEFAULT_SAMPLES_PER_SYMBOL
    )

    decoded = demodulate_symbols(
        iq,
        "BPSK"
    )

    assert decoded == original

    print(
        "✅ BPSK test passed"
    )


def test_qpsk():

    original = "10110010"

    symbols = []

    for i in range(
        0,
        len(original),
        2
    ):

        first = int(
            original[i]
        )

        second = int(
            original[i + 1]
        )

        i_value = (
            2 * first - 1
        )

        q_value = (
            2 * second - 1
        )

        symbols.append(
            (
                i_value
                + 1j * q_value
            )
            / np.sqrt(2)
        )

    symbols = np.array(
        symbols,
        dtype=np.complex64
    )

    iq = np.repeat(
        symbols,
        DEFAULT_SAMPLES_PER_SYMBOL
    )

    decoded = demodulate_symbols(
        iq,
        "QPSK"
    )

    assert decoded == original

    print(
        "✅ QPSK test passed"
    )


def test_8psk():

    original = "101100"

    symbols = []

    for i in range(
        0,
        len(original),
        3
    ):

        value = int(
            original[i:i + 3],
            2
        )

        phase = (
            2 * np.pi * value / 8
        )

        symbols.append(
            np.exp(1j * phase)
        )

    symbols = np.array(
        symbols,
        dtype=np.complex64
    )

    iq = np.repeat(
        symbols,
        DEFAULT_SAMPLES_PER_SYMBOL
    )

    decoded = demodulate_symbols(
        iq,
        "8-PSK"
    )

    assert decoded == original

    print(
        "✅ 8PSK test passed"
    )


def test_16qam():

    original = "10110010"

    mapping = {
        (0, 0): -3,
        (0, 1): -1,
        (1, 1): 1,
        (1, 0): 3
    }

    symbols = []

    for i in range(
        0,
        len(original),
        4
    ):

        i_value = mapping[
            (
                int(original[i]),
                int(original[i + 1])
            )
        ]

        q_value = mapping[
            (
                int(original[i + 2]),
                int(original[i + 3])
            )
        ]

        symbols.append(
            (
                i_value
                + 1j * q_value
            )
            / np.sqrt(10)
        )

    symbols = np.array(
        symbols,
        dtype=np.complex64
    )

    iq = np.repeat(
        symbols,
        DEFAULT_SAMPLES_PER_SYMBOL
    )

    decoded = demodulate_symbols(
        iq,
        "16-QAM"
    )

    assert decoded == original

    print(
        "✅ 16QAM test passed"
    )


